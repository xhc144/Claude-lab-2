"""第 15 集 懒标记及其复合：把标记看成函数"""

from episodes.common import *

A = [1, 2, 3, 4]


def build(S):
    S.cover("线段树同时支持“区间乘一个数”“区间加一个数”和“区间求和”。两种标记叠在一起时，谁先谁后？为什么下传是对的？",
            ["线段树的结点信息与合并（第 14 集）", "懒标记的基本思想：区间修改先记在结点上"])

    # ------------------------------------------------------------ 懒标记回顾
    S.section("懒标记在做什么")
    st = SegTree(4, x=640, y=200, w=900, level_h=170, node_h=62, vals=[f"和 {v}" for v in A], info_size=24)
    sums = {(1, 4): 10, (1, 2): 3, (3, 4): 7, (1, 1): 1, (2, 2): 2, (3, 3): 3, (4, 4): 4}
    for k, v in sums.items():
        st[k].label.tr["text"].base = f"和 {v}"
    S.show(st)
    S.say("区间修改如果把每个叶子都改一遍，一次就是 O(n)。懒标记的想法：修改区间被拆成 O(log n) 个结点，只在这些结点上{y|记一笔}。")
    S.note("区间修改：只在 O(log n) 个结点上打标记")
    S.say("这一笔叫标记，含义是“这个结点下面的所有元素，都还欠着这个操作”。结点自己的信息（和）立刻更新，儿子先不动。")
    S.note("标记 = 子树里所有元素“还欠着”的操作；结点自己的和已更新", color=Y)
    S.say("以后访问到它的儿子时，再把标记“下传”给两个儿子。于是有两个问题：标记怎样立刻更新结点的和？新旧标记怎样合并成一个？")
    S.note("问题一：标记如何更新结点信息？　问题二：新旧标记如何合并？", color=CY)

    # ------------------------------------------------------------ 标记是函数
    S.section("把标记看成函数")
    S.say("只有区间加时，标记是“加了多少”：两次加 3、加 5 合成加 8。和的更新：和 += 加的数 × 区间长度。")
    S.note("只有加：标记 = +b；合并：b1 + b2；和 += b × len")
    S.say("现在既有乘又有加。一串操作 ×2、+3、×5、+1 作用在 x 上，结果总是 a·x + b 的形式：")
    ops = ["x", "2x", "2x + 3", "10x + 15", "10x + 16"]
    opl = ["", "× 2", "+ 3", "× 5", "+ 1"]
    ts = []
    for i, (o, l) in enumerate(zip(ops, opl)):
        if l:
            ts.append(label(140 + 200 * i, 360, l, 26, O))
            ts.append(Line(140 + 200 * i - 40, 410, 140 + 200 * i + 40, 410, color=O, w=3, head=12))
        ts.append(label(240 + i * 200, 410, o, 30, Y if i == len(ops) - 1 else FG))
    S.play(FadeOut(st), dur=0.3)
    for t in ts:
        S.play(FadeIn(t, dy=8), dur=0.3)
    S.say("所以把标记写成一个函数 f(x) = a·x + b（先乘 a，再加 b）。任意多次乘、加复合起来，还是这种形式——这个形式对复合是{y|封闭}的。")
    S.note("{y|标记 = 函数 x → a·x + b}（先乘后加）", color=Y)
    S.say("问题一：标记作用在区间和上。区间里每个数都变成 a·x + b，和就变成 a·和 + b·长度。只用到和与长度，O(1)。")
    S.note("和 → a·和 + b·len")
    S.say("问题二：结点原有标记 (a₁, b₁)，又来了新操作 (a₂, b₂)。先做旧的再做新的：a₂(a₁·x + b₁) + b₂ = (a₁a₂)·x + (a₂b₁ + b₂)。")
    S.note("复合：(a₁, b₁) 再 (a₂, b₂) = (a₁a₂, a₂b₁ + b₂)", color=G)
    S.say("顺序很重要：先 ×2 再 +3 是 2x + 3，先 +3 再 ×2 是 2x + 6。新标记必须作用在旧标记“之后”。")
    S.note("顺序不能反：×2 后 +3 ≠ +3 后 ×2", color=R)
    S.say("为什么不用“先加后乘” a·(x + b) 的形式？在它后面再加 c 会变成 a·(x + b + c/a)，出现除法。在取模或整数下就麻烦了。")
    S.note("“先加后乘”形式复合要做除法 → 选“先乘后加”", color=DIM)

    # ------------------------------------------------------------ 演示
    S.section("一步步看标记的变化")
    S.note("标记 (×a, +b)：和 → a·和 + b·len", color=DIM)
    S.note("复合：(a₁, b₁) 再 (a₂, b₂) = (a₁a₂, a₂b₁ + b₂)", color=DIM)
    S.play(*[FadeOut(t) for t in ts], dur=0.3)
    st2 = SegTree(4, x=640, y=210, w=900, level_h=180, node_h=62, info_size=24)
    for k, v in sums.items():
        st2[k].label.tr["text"].base = f"和 {v}"
    S.show(st2)
    tags = {}
    for k, c in st2.nodes.items():
        if k[0] != k[1]:
            t = Text(c.g("x", 0) + c.box.g("w", 0) / 2 + 12, c.g("y", 0), "", size=22, color=O, anchor="lm")
        else:
            t = Text(c.g("x", 0), c.g("y", 0) + 84, "", size=22, color=O)
        t.tr["op"].base = 0.0
        st2.add(t)
        tags[k] = t
    arr = Array(A, x=640, y=790, cw=90, ch=56, gap=8, size=28, index=False)
    al = label(300, 790, "真实值", 22, DIM, anchor="rm")
    S.show(arr, al)
    S.say("例子：a = 1, 2, 3, 4。操作一：整个区间 ×2。[1, 4] 正好是根，只在根上打标记 (×2, +0)，根的和变成 2 × 10 = 20。")
    S.play(st2[(1, 4)].to(text="和 20", stroke=Y, sw=3), FadeIn(tags[(1, 4)]), tags[(1, 4)].to(text="标记 ×2 +0"), dur=0.6)
    S.play(*[arr.cells[i].to(text=str(A[i] * 2)) for i in range(4)], dur=0.5)
    S.play(st2[(1, 4)].to(stroke=LINE2, sw=2), dur=0.2)
    S.say("儿子们的和还是旧的 3 和 7——它们“欠着”根上的 ×2。这没关系，因为只要不访问它们，就没人看到旧值。")
    S.play(st2[(1, 2)].flash(R), st2[(3, 4)].flash(R), dur=0.8)
    S.say("操作二：[1, 2] 加 3。要走到 [1, 2]，先把根的标记下传：两个儿子的和各自 ×2，标记 (×2, +0) 复合到它们原来的空标记上。")
    S.play(st2.edges[((1, 4), (1, 2))].to(color=Y, w=4), st2.edges[((1, 4), (3, 4))].to(color=Y, w=4), dur=0.4)
    S.play(st2[(1, 2)].to(text="和 6"), st2[(3, 4)].to(text="和 14"), FadeIn(tags[(1, 2)]), FadeIn(tags[(3, 4)]),
           tags[(1, 2)].to(text="标记 ×2 +0"), tags[(3, 4)].to(text="标记 ×2 +0"), FadeOut(tags[(1, 4)]), dur=0.6)
    S.play(st2.edges[((1, 4), (1, 2))].to(color=LINE2, w=2.5), st2.edges[((1, 4), (3, 4))].to(color=LINE2, w=2.5), dur=0.2)
    S.note("下传：儿子的和用父标记更新，父标记复合到儿子标记之后，父标记清空")
    S.say("然后给 [1, 2] 加 3：和 = 6 + 3 × 2 = 12；标记复合：(×2, +0) 之后再 (×1, +3)，得到 (×2, +3)。根的和重新合并：12 + 14 = 26。")
    S.play(st2[(1, 2)].to(text="和 12", stroke=Y, sw=3), tags[(1, 2)].to(text="标记 ×2 +3"), dur=0.6)
    S.play(st2[(1, 4)].to(text="和 26"), st2[(1, 2)].to(stroke=LINE2, sw=2), dur=0.4)
    S.play(arr.cells[0].to(text="5"), arr.cells[1].to(text="7"), dur=0.5)
    S.say("操作三：查询 a[1]。走到叶子前，[1, 2] 的标记 (×2, +3) 下传：1 → 2×1+3 = 5，2 → 2×2+3 = 7，和 5 + 7 = 12，正好对上。")
    S.play(FadeIn(tags[(1, 1)]), FadeIn(tags[(2, 2)]), tags[(1, 1)].to(text="×2 +3"), tags[(2, 2)].to(text="×2 +3"),
           FadeOut(tags[(1, 2)]), dur=0.5)
    S.play(st2[(1, 1)].to(text="和 5", fill=tint(G, 0.35)), st2[(2, 2)].to(text="和 7"), dur=0.5)
    S.say("右边的 [3, 4] 一直没被访问，它的标记 (×2, +0) 还挂着，叶子 3、4 里还是旧值——但它们的真实值 6、8 已经体现在 [3, 4] 的和 14 里了。")
    S.play(st2[(3, 3)].flash(O), st2[(4, 4)].flash(O), dur=0.8)

    # ------------------------------------------------------------ 为什么对
    S.section("下传为什么是对的")
    S.say("关键是一个不变式：在任何一条从根到叶子的路径上，{y|越深的标记越旧}。")
    S.note("不变式：根到叶子的路径上，越深的标记越旧", color=Y)
    S.say("原因：要给某个结点打新标记，必须先从根走下来，沿路把祖先的标记都下传掉。所以新标记打下去时，它上面没有更老的标记。")
    S.say("于是叶子的真实值 = 把路径上的标记从深到浅依次作用上去。下传只是把父亲的标记接在儿子标记的后面，作用顺序没有改变。")
    S.note("真实值 = 路径上的标记从深到浅依次作用；下传不改变顺序")
    S.say("能用懒标记的一般条件有三条：")
    S.note("① 标记对复合封闭（两次操作能合成一个标记）", color=G)
    S.note("② 标记能直接更新结点信息（不看儿子）", color=G)
    S.note("③ 先合并再作用 = 先作用再合并", color=G)
    S.say("第三条是说：对父亲的和作用标记，等于对两个儿子分别作用再相加：a(L + R) + b(lenL + lenR) = (aL + b·lenL) + (aR + b·lenR)。")
    S.say("反例：区间开平方根，区间求和。√a + √b ≠ √(a + b)，只知道区间和，算不出开方以后的和——条件②不成立，不能打懒标记。")
    S.note("反例：区间开方 + 区间和（√a + √b ≠ √(a+b)）✗", color=R)

    # ------------------------------------------------------------ 手推题
    S.quiz("线段树要支持三种区间操作：赋值为 c、加上 c、求和。\n\n"
           "(1) 能不能也用“x → a·x + b”这种标记？赋值对应哪个 (a, b)？\n"
           "(2) 结点原标记是 (×3, +1)，先来一个“赋值为 5”，再来一个“加 2”，复合后的标记是什么？", think=20)
    S.say("(1) 能。赋值为 c 就是 x → 0·x + c，即 (a, b) = (0, c)。乘 0 把旧值完全清掉。")
    S.note("(1) 赋值 c = (×0, +c)", color=Y)
    S.say("(2) 按复合公式：(3, 1) 再 (0, 5) = (3×0, 0×1 + 5) = (0, 5)——旧标记被清空，符合直觉。")
    S.note("(×3, +1) 再 (×0, +5) = (×0, +5)")
    S.say("再 (1, 2)：(0×1, 1×5 + 2) = (0, 7)。意思是“整段都变成 7”，正确。")
    S.note("再 (×1, +2) = (×0, +7)：整段变成 7", color=G)
    S.say("把标记看成函数、用函数复合来合并，三种操作统一成了一种，下传的正确性也是同一个论证。", extra=0.5)

    S.recap([
        "懒标记：区间修改只在 O(log n) 个结点上记“欠着的操作”，结点自己的信息立刻更新，访问儿子时再下传。",
        "乘、加同时存在时，标记写成函数 x → a·x + b（先乘后加），复合 (a₁, b₁) 再 (a₂, b₂) = (a₁a₂, a₂b₁ + b₂)。",
        "正确性：根到叶子路径上越深的标记越旧，下传不改变作用顺序。",
        "可用条件：标记对复合封闭、能直接更新信息、与合并可交换；区间开方就不满足。",
    ], next_title="扫描线：矩形面积并")
